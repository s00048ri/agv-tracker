# ---- reproducibility (Done-when #2) ----

def test_generator_check_mode_passes_on_clean_tree():
    result = subprocess.run(
        [sys.executable, str(GENERATOR), "--check"],
        capture_output=True, text=True,
    )
    assert result.returncode == 0, (
        "generator --check failed on committed tree:\n"
        f"stdout: {result.stdout}\nstderr: {result.stderr}"
    )


def test_generator_is_deterministic(tmp_path):
    """Regenerating against the same data should yield byte-identical pages."""
    # Snapshot the current page bodies.
    before = {p.name: p.read_bytes() for p in VENUES_DIR.glob("*.md")
              if p.name != "index.md"}
    # Regenerate in place.
    result = subprocess.run(
        [sys.executable, str(GENERATOR)],
        capture_output=True, text=True,
    )
    assert result.returncode == 0, result.stderr
    after = {p.name: p.read_bytes() for p in VENUES_DIR.glob("*.md")
             if p.name != "index.md"}
    assert before == after, "regenerated pages differ from committed versions"


# ---- verificationBadge / evidencePanel contract ----

def test_verification_badge_handles_both_states():
    body = (COMPONENTS_DIR / "verificationBadge.js").read_text(encoding="utf-8")
    # Both branches must exist: verified + awaiting
    assert "Human-verified" in body
    assert "Awaiting human review" in body
    # Pulls reviewer out of human_verification evidence rows
    assert "human_verification" in body


def test_evidence_panel_distinguishes_source_types():
    body = (COMPONENTS_DIR / "evidencePanel.js").read_text(encoding="utf-8")
    for key in (
        "human_verification", "llm_classification", "official_site",
        "oecd_navigator", "iapp_tracker", "unesco_gaigo",
    ):
        assert key in body, key
    # Confidence colour map keys (JS object-literal keys can be bare or quoted)
    for level in ("high", "medium", "low"):
        assert re.search(rf"\b{level}\b\s*:", body), level


def test_evidence_panel_groups_by_field_name():
    body = (COMPONENTS_DIR / "evidencePanel.js").read_text(encoding="utf-8")
    assert "field_name" in body
    assert re.search(r"byField\.set|byField\.get", body)
